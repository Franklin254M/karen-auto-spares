do $$
begin
  if not exists (
    select 1
    from pg_type type_record
    join pg_namespace namespace_record on namespace_record.oid = type_record.typnamespace
    where type_record.typname = 'user_role'
      and namespace_record.nspname = 'public'
  ) then
    create type public.user_role as enum ('admin', 'sales_agent');
  end if;
end
$$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default 'Team member',
  role public.user_role not null default 'sales_agent',
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  acronym text not null,
  barcode text unique not null,
  category text not null default 'General',
  stock integer not null default 0 check (stock >= 0),
  reorder_level integer not null default 5 check (reorder_level >= 0),
  cost numeric(12,2) not null default 0,
  price numeric(12,2) not null default 0,
  supplier text,
  image_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.sales (
  id bigint generated by default as identity primary key,
  receipt_no text unique not null,
  product_id bigint not null references public.products(id),
  agent_id uuid not null references public.profiles(id),
  agent_name text not null,
  qty integer not null check (qty > 0),
  total numeric(12,2) not null,
  profit numeric(12,2) not null,
  created_at timestamptz not null default now()
);

create table if not exists public.returns (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id),
  receipt_no text,
  agent_id uuid not null references public.profiles(id),
  agent_name text not null,
  qty integer not null check (qty > 0),
  type text not null check (type in ('Return', 'Warranty')),
  reason text not null,
  notes text,
  status text not null default 'Open' check (status in ('Open', 'Approved', 'Rejected', 'Resolved')),
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin') $$;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$ begin insert into public.profiles (id, full_name, role) values (new.id, coalesce(new.raw_user_meta_data->>'full_name', 'Team member'), 'sales_agent'); return new; end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

