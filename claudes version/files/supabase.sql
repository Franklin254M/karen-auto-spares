create or replace function public.record_return(
  p_product_id bigint,
  p_receipt_no text,
  p_qty integer,
  p_type text,
  p_reason text,
  p_notes text default null
)
returns public.returns
language plpgsql
security definer
set search_path = public
as $$
declare
  sale_total integer;
  agent_profile public.profiles;
  return_record public.returns;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if p_qty is null or p_qty <= 0 or p_qty <> trunc(p_qty) then raise exception 'Quantity must be a positive whole number'; end if;
  if p_type not in ('Return', 'Warranty') then raise exception 'Invalid return type'; end if;
  if length(trim(coalesce(p_reason, ''))) < 2 then raise exception 'A return reason is required'; end if;

  select * into agent_profile from public.profiles where id = auth.uid();
  if agent_profile.id is null then raise exception 'Profile not found'; end if;
  if p_receipt_no is not null then
    select coalesce(sum(qty), 0) into sale_total from public.sales where receipt_no = p_receipt_no and product_id = p_product_id and (public.is_admin() or agent_id = auth.uid());
    if sale_total < p_qty then raise exception 'Return quantity exceeds the recorded sale'; end if;
  end if;

  insert into public.returns (product_id, receipt_no, agent_id, agent_name, qty, type, reason, notes)
  values (p_product_id, nullif(trim(p_receipt_no), ''), auth.uid(), agent_profile.full_name, p_qty, p_type, trim(p_reason), nullif(trim(p_notes), ''))
  returning * into return_record;
  return return_record;
end;
$$;

revoke all on function public.record_return(bigint, text, integer, text, text, text) from public;
grant execute on function public.record_return(bigint, text, integer, text, text, text) to authenticated;

create or replace function public.record_sale(
  p_product_id bigint,
  p_qty integer,
  p_sale_price numeric default null
)
returns public.sales
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_product public.products;
  agent_profile public.profiles;
  final_price numeric(12,2);
  sale_record public.sales;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if p_qty is null or p_qty <= 0 then raise exception 'Quantity must be greater than zero'; end if;
  if p_qty <> trunc(p_qty) then raise exception 'Quantity must be a whole number'; end if;

  select * into agent_profile from public.profiles where id = auth.uid();
  if agent_profile.id is null then raise exception 'Profile not found'; end if;

  select * into selected_product from public.products where id = p_product_id for update;
  if selected_product.id is null then raise exception 'Product not found'; end if;
  if selected_product.stock < p_qty then raise exception 'Insufficient stock'; end if;
  final_price := coalesce(p_sale_price, selected_product.price);
  if final_price < selected_product.cost then raise exception 'Selling price cannot be below incoming cost'; end if;

  update public.products set stock = stock - p_qty where id = selected_product.id;
  insert into public.sales (receipt_no, product_id, agent_id, agent_name, qty, total, profit)
  values (
    'SL-' || to_char(clock_timestamp(), 'YYYYMMDDHH24MISSMS') || '-' || lpad((floor(random() * 1000))::text, 3, '0'),
    selected_product.id, auth.uid(), agent_profile.full_name, p_qty,
    round(final_price * p_qty, 2), round((final_price - selected_product.cost) * p_qty, 2)
  ) returning * into sale_record;
  return sale_record;
end;
$$;

revoke all on function public.record_sale(bigint, integer, numeric) from public;
grant execute on function public.record_sale(bigint, integer, numeric) to authenticated;

